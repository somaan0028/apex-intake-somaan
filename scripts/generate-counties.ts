/**
 * Generate `lib/us-counties.ts` from `us_cities.json`.
 *
 * The source maps state -> county -> [cities]. We only need the county names,
 * keyed by state code, so this strips the county-equivalent suffix
 * ("County"/"Parish"/"Borough"/"Census Area") and normalises a few odd keys
 * (e.g. "Denver, City and County of" -> "Denver", "Anchorage, Municipality of"
 * -> "Anchorage").
 *
 * Run: `npm run geo:generate`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { US_STATES } from "../lib/us-states";

const SOURCE = path.join(process.cwd(), "us_cities.json");
const TARGET = path.join(process.cwd(), "lib", "us-counties.ts");

type Source = Record<string, Record<string, string[]>>;

/** Strip the county-equivalent suffix, e.g. "Orleans Parish" -> "Orleans". */
function toCountyName(key: string): string {
  return key
    .replace(
      /,\s*(?:city and county of|municipality of|city and borough of|borough of|city of)$/i,
      "",
    )
    .replace(/\s+(?:county|parish|borough|census area)$/i, "")
    .trim();
}

const source = JSON.parse(readFileSync(SOURCE, "utf8")) as Source;
const codeByName = new Map(
  US_STATES.map((state) => [state.name.toLowerCase(), state.code]),
);

const byState = new Map<string, Set<string>>();
for (const [stateName, counties] of Object.entries(source)) {
  const code = codeByName.get(stateName.trim().toLowerCase());
  if (!code) {
    throw new Error(`us_cities.json has an unknown state: ${stateName}`);
  }
  const names = byState.get(code) ?? new Set<string>();
  for (const key of Object.keys(counties)) names.add(toCountyName(key));
  byState.set(code, names);
}

const body = US_STATES.map((state) => {
  const names = [...(byState.get(state.code) ?? [])].sort((a, b) =>
    a.localeCompare(b),
  );
  const entries = names.map((name) => `    ${JSON.stringify(name)},`).join("\n");
  return `  ${state.code}: [\n${entries}\n  ],`;
}).join("\n");

const output = `/**
 * County (and county-equivalent) names per US state, keyed by state code.
 *
 * GENERATED by \`scripts/generate-counties.ts\` from \`us_cities.json\` — do not
 * edit by hand; run \`npm run geo:generate\` to refresh. The trailing
 * "County"/"Parish"/"Borough"/"Census Area" suffix is stripped, so entries are
 * bare names ("Los Angeles", "Orleans", "Denver").
 */
export const COUNTIES_BY_STATE: Record<string, readonly string[]> = {
${body}
};
`;

writeFileSync(TARGET, output);
const total = [...byState.values()].reduce((n, set) => n + set.size, 0);
console.log(`[geo] Wrote ${TARGET} — ${total} counties across ${byState.size} states.`);
