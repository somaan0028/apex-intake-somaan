/**
 * Prepare a clone to run.
 *
 * The setup contract is intentionally small: write an `env` file with the two
 * required secrets, then make sure the SQLite database exists and is seeded.
 * Optional settings are read from the environment or `.env.local`, so the
 * generated `.env` never grows beyond what the app cannot boot without.
 *
 * Existing real values are kept. Values passed on the command line win, which
 * makes `OPENROUTER_API_KEY=... CANDIDATE_TOKEN=... npm run setup` work.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ensureDatabase } from "../lib/db/bootstrap";

const PLACEHOLDER_PREFIX = "replace-with-";

const required = [
  {
    key: "OPENROUTER_API_KEY",
    placeholder: "replace-with-your-openrouter-key",
  },
  {
    key: "CANDIDATE_TOKEN",
    placeholder: "replace-with-your-brightwater-token",
  },
] as const;

const envPath = path.join(process.cwd(), ".env");
const localEnvPath = path.join(process.cwd(), ".env.local");

/** Read a dotenv-style file into a map. Comments and blank lines are ignored. */
function readEnvValues(filePath: string): Map<string, string> {
  const values = new Map<string, string>();
  if (!existsSync(filePath)) return values;

  for (const line of readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (!match) continue;
    values.set(match[1], match[2].replace(/^["']|["']$/g, "").trim());
  }
  return values;
}

const existing = readEnvValues(envPath);
const local = readEnvValues(localEnvPath);

// Keep a custom database location working even though it does not belong in
// the generated `.env`. It can come from the shell, `.env.local`, or a value
// left behind by an older setup file.
const databasePath =
  process.env.DATABASE_PATH?.trim() ||
  local.get("DATABASE_PATH")?.trim() ||
  existing.get("DATABASE_PATH")?.trim();
if (databasePath) {
  process.env.DATABASE_PATH = databasePath;
}

const lines = [
  "# Generated by npm run setup. Only the required keys belong in this file.",
  "# Replace the placeholders to enable the AI assistant and Brightwater sends.",
];
let placeholders = 0;

for (const { key, placeholder } of required) {
  const passed = process.env[key]?.trim();
  const saved = existing.get(key)?.trim();
  const realSaved = saved && !saved.startsWith(PLACEHOLDER_PREFIX) ? saved : "";
  const value = passed || realSaved || placeholder;

  if (value === placeholder) placeholders += 1;
  lines.push(`${key}=${value}`);
}

writeFileSync(envPath, `${lines.join("\n")}\n`, "utf8");
console.log(`[setup] Wrote ${path.basename(envPath)} with 2 required keys.`);

if (placeholders > 0) {
  console.log(
    "[setup] Some values are placeholders. Replace them in .env to use the AI assistant and Brightwater sends.",
  );
}

console.log("[setup] Preparing the database...");
ensureDatabase();
